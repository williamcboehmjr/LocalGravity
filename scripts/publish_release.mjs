#!/usr/bin/env node
/**
 * LocalGravity Autonomous Release & Distribution Engine
 *
 * Fully automates the complete release lifecycle:
 * 1. Verifies TypeScript compilation for Client and Server
 * 2. Bumps semver version across client/package.json, server/package.json, and tauri.conf.json
 * 3. Builds signed Windows MSI installer with cryptographic minisign signatures
 * 4. Signs macOS DMG with updater private key
 * 5. Generates updater manifest `latest.json`
 * 6. Commits changes to Git and pushes to GitHub
 * 7. Publishes GitHub Release with all binary assets & signatures
 */

import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const clientDir = path.join(rootDir, 'client');
const serverDir = path.join(rootDir, 'server');
const tauriConfPath = path.join(clientDir, 'src-tauri', 'tauri.conf.json');
const clientPkgPath = path.join(clientDir, 'package.json');
const serverPkgPath = path.join(serverDir, 'package.json');
const keyPath = path.join(clientDir, 'src-tauri', 'localgravity-updater.key');

function parseArgs() {
  const args = process.argv.slice(2);
  let bumpType = 'patch';
  let notes = '';
  let skipLinux = false;
  let skipAndroid = false;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--bump' && args[i + 1]) {
      bumpType = args[++i];
    } else if (args[i] === '--notes' && args[i + 1]) {
      notes = args[++i];
    } else if (args[i].startsWith('--notes=')) {
      notes = args[i].slice('--notes='.length);
    } else if (args[i] === '--skip-linux') {
      skipLinux = true;
    } else if (args[i] === '--skip-android') {
      skipAndroid = true;
    } else if (!notes && !args[i].startsWith('--')) {
      notes = args[i];
    }
  }

  return { bumpType, notes, skipLinux, skipAndroid };
}

function calculateNextVersion(currentVersion, bumpType) {
  if (/^\d+\.\d+\.\d+$/.test(bumpType)) {
    return bumpType;
  }
  const parts = currentVersion.split('.').map((n) => parseInt(n, 10));
  if (parts.length !== 3 || parts.some(isNaN)) {
    throw new Error(`Invalid semver: ${currentVersion}`);
  }
  let [major, minor, patch] = parts;
  if (bumpType === 'major') {
    major += 1;
    minor = 0;
    patch = 0;
  } else if (bumpType === 'minor') {
    minor += 1;
    patch = 0;
  } else {
    patch += 1;
  }
  return `${major}.${minor}.${patch}`;
}

async function main() {
  console.log('==================================================================');
  console.log('🚀 LocalGravity Autonomous Release & Distribution Engine');
  console.log('==================================================================');

  const { bumpType, notes: rawNotes, skipLinux, skipAndroid } = parseArgs();
  if (!fs.existsSync(keyPath)) {
    throw new Error(`Signing key not found at ${keyPath}`);
  }

  const clientPkg = JSON.parse(fs.readFileSync(clientPkgPath, 'utf8'));
  const currentVersion = clientPkg.version;
  const newVersion = calculateNextVersion(currentVersion, bumpType);
  const tag = `v${newVersion}`;
  const notes = rawNotes || `LocalGravity ${tag} Release with autonomous enhancements and fixes.`;

  console.log(`Current version: ${currentVersion}`);
  console.log(`Target release : ${tag}`);
  console.log(`Release notes  : ${notes}\n`);

  // Step 1: Verify compilation of client and server
  console.log('--- Step 1/6: Verifying Clean Build (Client & Server) ---');
  execSync('npm run build', { cwd: clientDir, stdio: 'inherit' });
  execSync('npm run build', { cwd: serverDir, stdio: 'inherit' });
  console.log(' Build checks passed cleanly.\n');

  // Step 2: Update version numbers
  console.log('--- Step 2/6: Bumping Versions in package.json & tauri.conf.json ---');
  clientPkg.version = newVersion;
  fs.writeFileSync(clientPkgPath, JSON.stringify(clientPkg, null, 2) + '\n', 'utf8');

  if (fs.existsSync(serverPkgPath)) {
    const serverPkg = JSON.parse(fs.readFileSync(serverPkgPath, 'utf8'));
    serverPkg.version = newVersion;
    fs.writeFileSync(serverPkgPath, JSON.stringify(serverPkg, null, 2) + '\n', 'utf8');
  }

  const tauriConf = JSON.parse(fs.readFileSync(tauriConfPath, 'utf8'));
  tauriConf.version = newVersion;
  fs.writeFileSync(tauriConfPath, JSON.stringify(tauriConf, null, 2) + '\n', 'utf8');

  // Sync Android tauri.properties versionName and versionCode
  const androidPropsPath = path.join(clientDir, 'src-tauri', 'gen', 'android', 'app', 'tauri.properties');
  if (fs.existsSync(androidPropsPath)) {
    const [maj, min, pat] = newVersion.split('.').map((n) => parseInt(n, 10) || 0);
    const versionCode = maj * 1000000 + min * 1000 + pat;
    fs.writeFileSync(
      androidPropsPath,
      `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\ntauri.android.versionName=${newVersion}\ntauri.android.versionCode=${versionCode}\n`,
      'utf8'
    );
  }

  // Also sync fallback version strings in updaterService.ts and SettingsModal.tsx
  const updaterSvcPath = path.join(clientDir, 'src', 'services', 'updaterService.ts');
  if (fs.existsSync(updaterSvcPath)) {
    const svcSrc = fs.readFileSync(updaterSvcPath, 'utf8');
    fs.writeFileSync(
      updaterSvcPath,
      svcSrc.replace(/let currentVersion = '[^']+';/, `let currentVersion = '${newVersion}';`),
      'utf8'
    );
  }
  const settingsModalPath = path.join(clientDir, 'src', 'components', 'left-rail', 'SettingsModal.tsx');
  if (fs.existsSync(settingsModalPath)) {
    const modalSrc = fs.readFileSync(settingsModalPath, 'utf8');
    fs.writeFileSync(
      settingsModalPath,
      modalSrc.replace(/useState<string>\('\d+\.\d+\.\d+'\)/, `useState<string>('${newVersion}')`),
      'utf8'
    );
  }
  console.log(` Bumped version to ${newVersion} across all manifests.\n`);

  // Step 3: Build Windows MSI + Updater Signature
  console.log('--- Step 3/6: Building Signed Windows MSI ---');
  const privateKey = fs.readFileSync(keyPath, 'utf8').trim();
  const buildEnv = {
    ...process.env,
    TAURI_SIGNING_PRIVATE_KEY: privateKey,
    TAURI_SIGNING_PRIVATE_KEY_PASSWORD: '',
  };
  execSync('npx tauri build --bundles msi', {
    cwd: clientDir,
    stdio: 'inherit',
    env: buildEnv,
  });

  const msiPath = path.join(
    clientDir,
    'src-tauri',
    'target',
    'release',
    'bundle',
    'msi',
    `LocalGravity_${newVersion}_x64_en-US.msi`
  );
  const msiSigPath = `${msiPath}.sig`;

  if (!fs.existsSync(msiPath) || !fs.existsSync(msiSigPath)) {
    throw new Error(`Expected MSI or signature missing at ${msiPath}`);
  }
  const winSignature = fs.readFileSync(msiSigPath, 'utf8').trim();
  console.log(` Windows MSI and signature verified: ${path.basename(msiPath)}\n`);

  // Step 4: Build Local Hybrid Artifacts (Android arm64 APK + WSL2 Linux x64 DEB/AppImage)
  console.log('--- Step 4/6: Building Local Android APK & WSL2 Linux x64 Bundles ---');
  const apkPath = path.join(rootDir, `LocalGravity_${newVersion}_arm64.apk`);
  const androidSdkDir = fs.existsSync('C:\\Android\\Sdk')
    ? 'C:\\Android\\Sdk'
    : path.join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk');
  const keystorePropsPath = path.join(clientDir, 'src-tauri', 'keystore.properties');

  if (!skipAndroid && process.platform === 'win32' && fs.existsSync(androidSdkDir) && fs.existsSync(keystorePropsPath)) {
    console.log('Building signed Android arm64 APK locally...');
    const ndkRoot = path.join(androidSdkDir, 'ndk');
    const ndkVersions = fs.existsSync(ndkRoot) ? fs.readdirSync(ndkRoot).sort().reverse() : [];
    const ndkHome = ndkVersions.length > 0 ? path.join(ndkRoot, ndkVersions[0]) : '';
    const javaHome = fs.existsSync('C:\\Program Files\\Java\\jdk-20')
      ? 'C:\\Program Files\\Java\\jdk-20'
      : process.env.JAVA_HOME || '';
    const androidEnv = {
      ...process.env,
      ANDROID_HOME: androidSdkDir,
      ANDROID_SDK_ROOT: androidSdkDir,
      ...(ndkHome ? { NDK_HOME: ndkHome } : {}),
      ...(javaHome ? { JAVA_HOME: javaHome } : {}),
    };

    try {
      execSync(`npx tauri android build --apk --target aarch64`, {
        cwd: clientDir,
        stdio: 'inherit',
        env: androidEnv,
      });
    } catch {
      console.log('Tauri android build hit Windows symlink restriction or completed Rust compile; copying .so and running Gradle...');
    }

    const soSrc = path.join(
      clientDir,
      'src-tauri',
      'target',
      'aarch64-linux-android',
      'release',
      'liblocalgravity_edge_lib.so'
    );
    const jniDir = path.join(
      clientDir,
      'src-tauri',
      'gen',
      'android',
      'app',
      'src',
      'main',
      'jniLibs',
      'arm64-v8a'
    );
    if (!fs.existsSync(soSrc)) {
      throw new Error(`Android release library missing at ${soSrc}`);
    }
    fs.mkdirSync(jniDir, { recursive: true });
    fs.copyFileSync(soSrc, path.join(jniDir, 'liblocalgravity_edge_lib.so'));

    const androidProjDir = path.join(clientDir, 'src-tauri', 'gen', 'android');
    execSync('.\\gradlew.bat assembleArm64Release -x rustBuildArm64Release', {
      cwd: androidProjDir,
      stdio: 'inherit',
      env: androidEnv,
    });

    const apkOutDir = path.join(androidProjDir, 'app', 'build', 'outputs', 'apk', 'arm64', 'release');
    const builtApks = fs.existsSync(apkOutDir)
      ? fs.readdirSync(apkOutDir).filter((f) => f.endsWith('.apk'))
      : [];
    if (builtApks.length === 0) {
      throw new Error(`No APK output found in ${apkOutDir}`);
    }
    fs.copyFileSync(path.join(apkOutDir, builtApks[0]), apkPath);
    console.log(` Android arm64 APK built: ${path.basename(apkPath)}\n`);
  } else if (skipAndroid) {
    console.log(' Skipping local Android APK build (--skip-android).\n');
  } else {
    console.log(' Android SDK or keystore.properties not found; skipping local APK build.\n');
  }

  let linuxDebPath = '';
  let linuxAppImagePath = '';
  let linuxAppImageSigPath = '';
  let linuxX64Signature = '';
  const linuxOutDir = path.join(rootDir, 'dist-release', 'linux-x64');

  if (!skipLinux && process.platform === 'win32') {
    const toWslPath = (winPath) => {
      const m = winPath.match(/^([A-Za-z]):[\\/](.*)$/);
      if (!m) return winPath.replace(/\\/g, '/');
      return `/mnt/${m[1].toLowerCase()}/${m[2].replace(/\\/g, '/')}`;
    };
    const wslScriptPath = toWslPath(path.join(rootDir, 'scripts', 'build-linux-wsl.sh'));
    console.log(`Building Linux x64 (.deb + .AppImage) via WSL2 Ubuntu (${wslScriptPath})...`);
    execSync(`wsl -d Ubuntu -- bash "${wslScriptPath}"`, {
      cwd: rootDir,
      stdio: 'inherit',
    });

    if (fs.existsSync(linuxOutDir)) {
      const entries = fs.readdirSync(linuxOutDir);
      const debEntry =
        entries.find((f) => f.includes(`_${newVersion}_`) && f.endsWith('.deb')) ||
        entries.find((f) => f.endsWith('.deb'));
      const appImageEntry =
        entries.find((f) => f.includes(`_${newVersion}_`) && f.endsWith('.AppImage')) ||
        entries.find((f) => f.endsWith('.AppImage'));
      if (debEntry) linuxDebPath = path.join(linuxOutDir, debEntry);
      if (appImageEntry) {
        linuxAppImagePath = path.join(linuxOutDir, appImageEntry);
        const sigCandidate = `${linuxAppImagePath}.sig`;
        if (fs.existsSync(sigCandidate)) {
          linuxAppImageSigPath = sigCandidate;
          linuxX64Signature = fs.readFileSync(sigCandidate, 'utf8').trim();
        }
      }
    }
    console.log(
      ` Linux x64 artifacts ready: deb=${linuxDebPath ? path.basename(linuxDebPath) : 'none'}, appimage=${
        linuxAppImagePath ? path.basename(linuxAppImagePath) : 'none'
      }\n`
    );
  } else if (skipLinux) {
    console.log(' Skipping local WSL2 Linux x64 build (--skip-linux).\n');
  }

  // Step 5: Generate initial honest latest.json updater manifest (only include platforms with real signatures!)
  // GitHub Actions finalize-manifest will merge macOS Universal and Linux ARM64 once those jobs upload.
  console.log('--- Step 5/6: Generating Honest Updater Manifest (latest.json) ---');
  const platforms = {
    'windows-x86_64': {
      signature: winSignature,
      url: `https://github.com/williamcboehmjr/LocalGravity/releases/download/${tag}/${path.basename(msiPath)}`,
    },
  };

  if (linuxAppImagePath && linuxX64Signature) {
    platforms['linux-x86_64'] = {
      signature: linuxX64Signature,
      url: `https://github.com/williamcboehmjr/LocalGravity/releases/download/${tag}/${path.basename(linuxAppImagePath)}`,
    };
  }

  if (fs.existsSync(apkPath)) {
    platforms['android-aarch64'] = {
      signature: '',
      url: `https://github.com/williamcboehmjr/LocalGravity/releases/download/${tag}/${path.basename(apkPath)}`,
    };
  }

  const manifest = {
    version: tag,
    notes,
    pub_date: new Date().toISOString(),
    platforms,
  };

  const latestJsonPath = path.join(rootDir, 'latest.json');
  fs.writeFileSync(latestJsonPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  console.log(` latest.json generated with platforms: ${Object.keys(platforms).join(', ')}.\n`);

  // Step 6: Git commit, push, and create GitHub release
  console.log('--- Step 6/6: Git Commit & GitHub Release Publish ---');
  execSync('git add -A', { cwd: rootDir, stdio: 'inherit' });
  execSync(`git commit -m "release: ${tag} - ${notes.slice(0, 72)}"`, {
    cwd: rootDir,
    stdio: 'inherit',
  });
  try { execSync('git pull --rebase -X ours origin main', { cwd: rootDir, stdio: 'inherit' }); } catch {}
  execSync('git push origin main', { cwd: rootDir, stdio: 'inherit' });

  const assets = [
    `"${msiPath}"`,
    `"${msiSigPath}"`,
    `"${latestJsonPath}"`,
  ];
  const trayExePath = path.join(rootDir, 'tray', 'tray.exe');
  if (fs.existsSync(trayExePath)) {
    assets.push(`"${trayExePath}"`);
  }
  if (linuxDebPath && fs.existsSync(linuxDebPath)) {
    assets.push(`"${linuxDebPath}"`);
  }
  if (linuxAppImagePath && fs.existsSync(linuxAppImagePath)) {
    assets.push(`"${linuxAppImagePath}"`);
  }
  if (linuxAppImageSigPath && fs.existsSync(linuxAppImageSigPath)) {
    assets.push(`"${linuxAppImageSigPath}"`);
  }
  if (fs.existsSync(apkPath)) {
    assets.push(`"${apkPath}"`);
  }

  const ghCmd = `gh release create ${tag} ${assets.join(' ')} --title "LocalGravity ${tag}" --notes "${notes.replace(/"/g, '\\"')}"`;
  console.log(`Publishing release via GitHub CLI...`);
  execSync(ghCmd, { cwd: rootDir, stdio: 'inherit' });

  // Best-effort restart of any locally running Central Brain daemon so new backend routes/handlers take effect immediately
  console.log('--- Reloading local Central Brain daemon (if running on port 3390) ---');
  try {
    await fetch('http://127.0.0.1:3390/api/gpu/offload', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: '{}',
      signal: AbortSignal.timeout(2000),
    }).catch(() => {});
    const restartRes = await fetch('http://127.0.0.1:3390/api/system/restart', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: '{}',
      signal: AbortSignal.timeout(2000),
    }).catch(() => null);
    if (restartRes && restartRes.ok) {
      console.log(' Triggered local Central Brain restart to load new server build.');
    } else {
      console.log(' Local Central Brain restart skipped (daemon offline or managed separately).');
    }
  } catch {
    console.log(' Local Central Brain restart skipped (daemon offline).');
  }

  console.log('==================================================================');
  console.log(`🎉 RELEASE ${tag} PUBLISHED SUCCESSFULLY TO GITHUB!`);
  console.log('==================================================================');
  console.log(`Users can now:`);
  console.log(`1. Click "Check for Updates" in their macOS or Windows desktop app.`);
  console.log(`2. The app will auto-download ${tag}, install, and restart.`);
  console.log('3. Or reload the WebUI on http://localhost:3390.');
  console.log('==================================================================\n');
}

main().catch((err) => {
  console.error('\n❌ Release failed:', err.message);
  process.exit(1);
});
